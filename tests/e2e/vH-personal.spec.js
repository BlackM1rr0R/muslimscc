import { test, expect, settle, expectCleanConsole } from './fixtures.js'

async function reach(page, testId) {
  const el = page.getByTestId(testId).first()
  for (let i = 0; i < 90 && !(await el.count()); i++) {
    await page.evaluate(() => window.scrollBy(0, 700))
    await page.waitForTimeout(120)
  }
  await el.scrollIntoViewIfNeeded()
  return el
}
const seedOnce = (page, data, tag = 'vh-seeded') => page.addInitScript(({ d, tag }) => {
  if (sessionStorage.getItem(tag)) return
  sessionStorage.setItem(tag, '1')
  for (const [k, v] of Object.entries(d)) localStorage.setItem(k, v)
}, { d: data, tag })
const order = (page) => page.locator('[data-home-section]').evaluateAll((els) => els.map((e) => e.getAttribute('data-home-section')))

test('ana səhifə: bölmələrin sırası və görünməsi yadda qalır', async ({ page, consoleProblems }) => {
  await page.goto('/')
  await settle(page)
  expect((await order(page)).slice(0, 3)).toEqual(['stories', 'today', 'myday'])
  await page.getByTestId('home-customize').click()
  const dlg = page.getByTestId('home-layout-editor')
  await expect(dlg).toBeVisible()
  // "Nə axtarırsınız?" ən yuxarıya — klaviatura alternativi (↑ düyməsi), fokus düymədə qalır
  const up = dlg.getByTestId('hl-up-quick')
  for (let i = 0; i < 4; i++) await up.click()
  await expect(dlg.getByTestId('hl-live')).toContainText('1 / 10')
  await expect(up).toBeDisabled()
  await expect(dlg.getByTestId('hl-down-quick')).toBeFocused()
  // Günün hekayələrini və "Bu gün" panelindəki ayəni gizlət
  await dlg.getByTestId('hl-show-stories').uncheck()
  await dlg.getByTestId('hl-show-ayah').uncheck()
  await dlg.getByTestId('hl-done').click()
  await expect(dlg).toBeHidden()
  const o1 = await order(page)
  expect(o1[0]).toBe('quick')
  expect(o1).not.toContain('stories')
  await page.reload()
  await settle(page)
  const o2 = await order(page)
  expect(o2[0]).toBe('quick')
  expect(o2).not.toContain('stories')
  await expect(page.locator('.hp-td-hadith')).toBeVisible()
  await expect(page.locator('.hp-td-ayah')).toHaveCount(0)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('home_layout_v1')))
  expect(saved.s.o[0]).toBe('quick')
  expect(saved.s.h).toEqual(['stories'])
  // Susmaya görə qaytar → açar silinir
  await page.getByTestId('home-customize').click()
  await page.getByTestId('hl-reset').click()
  await page.getByTestId('hl-done').click()
  expect((await order(page))[0]).toBe('stories')
  expect(await page.evaluate(() => localStorage.getItem('home_layout_v1'))).toBeNull()
  expectCleanConsole(consoleProblems)
})

