/** Terminin cari dildəki adı: az → term, ar → ərəbcə, ru/tr → bu fayl, en → translit. */
export function glossaryName(item, lang) {
  if (!item) return ''
  if (lang === 'az') return item.term
  if (lang === 'ar') return item.ar
  const n = GLOSSARY_NAMES[item.id]
  if (lang === 'ru') return (n && n[0]) || item.translit
  if (lang === 'tr') return (n && n[1]) || item.translit
  return item.translit
}

/** İngiliscə qarşılıq (varsa və translit-dən fərqlidirsə): "Salah" → "Prayer". */
export function glossaryGloss(item) {
  const g = item && GLOSSARY_NAMES[item.id]?.[2]
  return g && g.toLowerCase() !== String(item.translit).toLowerCase() ? g : ''
}
