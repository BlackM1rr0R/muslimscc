/** '{n} gün' → '3 gün' */
export const fill = (s, vars) => String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m))

const DATE_LOCALES = { en: 'en-GB', ru: 'ru-RU', tr: 'tr-TR', ar: 'ar-u-ca-gregory-nu-latn' }

/** '2026-10-30' → "30 oktyabr" / "30 October" (il fərqlidirsə il də) */
export function formatDay(key, lang, { withYear = false, weekday = false } = {}) {
  const [y, m, d] = key.split('-').map(Number)
  const date = new Date(y, m - 1, d, 12)
  const showYear = withYear || y !== new Date().getFullYear()
  if (lang === 'az') return `${d} ${AZ_MONTHS[m - 1]}${showYear ? ` ${y}` : ''}`
  const opts = { day: 'numeric', month: 'long', ...(showYear ? { year: 'numeric' } : {}), ...(weekday ? { weekday: 'short' } : {}) }
  try { return date.toLocaleDateString(DATE_LOCALES[lang] || 'en-GB', opts) } catch { return key }
}

export function formatMonth(year, month0, lang) {
  if (lang === 'az') return `${AZ_MONTHS[month0][0].toUpperCase()}${AZ_MONTHS[month0].slice(1)} ${year}`
  try {
    const s = new Date(year, month0, 15).toLocaleDateString(DATE_LOCALES[lang] || 'en-GB', { month: 'long', year: 'numeric' })
    return s.charAt(0).toUpperCase() + s.slice(1)
  } catch { return `${year}-${month0 + 1}` }
}
