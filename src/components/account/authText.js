/** "{n}" / "{email}" yer tutucularını doldur (ərəbcədə rəqəm ərəb-hind yazılışı ilə). */
export function fillText(s, lang, vars = {}) {
  return String(s || '').replace(/\{(\w+)\}/g, (m, k) => {
    const v = vars[k]
    if (v == null) return m
    return typeof v === 'number' && lang === 'ar' ? v.toLocaleString('ar-EG') : String(v)
  })
}
