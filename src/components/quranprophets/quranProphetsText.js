// Rus dili: 1 раз · 2–4 раза · 5+ раз (11–14 — раз)
const ruForm = (n, one, few, many) => {
  const m10 = n % 10, m100 = n % 100
  if (m10 === 1 && m100 !== 11) return one
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few
  return many
}
// Ərəb dili: 1 · 2 · 3–10 (cəm) · 11+ (tək)
const arForm = (n, one, two, few, many) => (n === 1 ? one : n === 2 ? two : n % 100 >= 3 && n % 100 <= 10 ? few : many)

