/** Server xətası → istifadəçi mətni */
export function khatmError(e, t) {
  if (!e || e instanceof TypeError) return t.err.net
  switch (e.code) {
    case 'rate_limited': return t.err.rate
    case 'too_soon': return t.err.tooSoon
    case 'expired': case 'no_claim': case 'not_yours': return t.err.expired
    case 'all_taken': return t.err.allTaken
    default: return e.status === 429 ? t.err.rate : t.err.unknown
  }
}

/** ms → (gün, saat, dəqiqə) mətni */
export function fmtDuration(ms, t) {
  const min = Math.max(1, Math.round((Number(ms) || 0) / 60000))
  const d = Math.floor(min / 1440), h = Math.floor((min % 1440) / 60), m = min % 60
  return t.dur(d, h, m)
}
