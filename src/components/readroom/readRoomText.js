/** Server xəta kodu → yazı açarı */
export function rtError(e, t) {
  const code = e && e.code
  if (e && e.status === 429) return t.err.rate
  if (code === 'invalid_invite' || code === 'not_found') return t.err.invite
  if (code === 'room_full') return t.err.full
  if (code === 'too_many') return t.err.tooMany
  if (code === 'bad_name') return t.err.name
  if (code === 'host_only') return t.err.host
  if (e instanceof TypeError) return t.err.net
  return t.err.unknown
}
